"""C13-15 ``framesamp_modul_client``: the real websocket client (``make_recording_client``), the transparent relay
(``relay`` subcommand) and the transport check (``transport_check`` / ``transport-check`` subcommand), plus timing
summaries and send/receive digests.

Everything runs on the 127.0.0.1 loopback: the fake policy server sends and receives with
``openpi_client.msgpack_numpy`` (same encoding as the real FrameSamp+Modulation server), and the relay is the production
``cmd_relay``. Expectations (frame counts, message counts, executed actions, per-kind counts) are hand-computed from this
file's fake environment and fake server, never generated by calling the functions under test.
"""
